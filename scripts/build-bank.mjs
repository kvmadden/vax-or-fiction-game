#!/usr/bin/env node
// Bank phase 2. Reads content/bank/metadata/<subject>.json (source of truth) and content/bank/approved/<subject>.json
// (empty in phase 2, populated by the phase 3 importer) and writes the generated runtime slice
// src/data/bank/metadata.generated.ts (BANK_META, BANK_COPIES), plus src/data/decks/bank/<subject>.ts for any
// subject that already has approved questions (none in phase 2).
//
// `--check` regenerates into memory and diffs against the committed file instead of writing, so CI can fail on a
// stale generated slice without ever touching the working tree (the natural-copy.test.ts:56 pattern, 4.9's
// "Generated slice" guard).
//
// Every record must carry a final difficulty (docs/QUESTION-DIFFICULTY-RUBRIC.md). The phase 2 pending placeholder
// is refused, in both modes, so a question can never reach the runtime slice without a rated level.
// Run: node --import tsx scripts/build-bank.mjs [--check]
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';

const CHECK = process.argv.includes('--check');
const METADATA_DIR = 'content/bank/metadata';
const OUT_PATH = 'src/data/bank/metadata.generated.ts';
const LEVELS = new Set(['easy', 'medium', 'hard', 'expert']);
const SOURCES = new Set(['rubric', 'play']);

/** Returns why a record's difficulty is not a final level, or null when it is. */
function difficultyProblem(record) {
  const d = record.difficulty;
  if (!d || typeof d !== 'object') return 'has no difficulty record';
  if (d.pending === true) return 'still carries the phase 2 pending placeholder';
  if (!LEVELS.has(d.level)) return `has no final level (found ${JSON.stringify(d.level)})`;
  if (!SOURCES.has(d.source)) return `has an unknown difficulty source ${JSON.stringify(d.source)}`;
  if (!Array.isArray(d.ratings) || d.ratings.length === 0) return 'has a level with no rating behind it';
  if (d.source === 'play' && (!d.play || typeof d.play !== 'object')) return 'has a play level with no play evidence';
  if (d.source === 'play' && (!Array.isArray(d.history) || d.history.length === 0)) return 'has a play level with no history entry for the move';
  return null;
}

function loadMetadataRecords() {
  if (!existsSync(METADATA_DIR)) throw new Error(`${METADATA_DIR} is missing. Run scripts/bank-backfill-metadata.mjs first.`);
  const records = [];
  for (const file of readdirSync(METADATA_DIR).filter((f) => f.endsWith('.json')).sort()) {
    const bySubject = JSON.parse(readFileSync(`${METADATA_DIR}/${file}`, 'utf8'));
    for (const record of Object.values(bySubject)) records.push(record);
  }
  records.sort((a, b) => a.bankId.localeCompare(b.bankId));
  return records;
}

function runtimeMetaFor(record) {
  return {
    subject: record.subject,
    kind: record.kind,
    textVersion: record.textVersion,
    difficulty: record.difficulty.level,
    conceptId: record.conceptId,
    rotation: record.rotation,
    status: record.status,
    skill: record.skill,
    audience: record.audience,
  };
}

function renderModule(records) {
  const meta = {};
  const copies = {};
  for (const record of records) {
    meta[record.bankId] = runtimeMetaFor(record);
    for (const copyId of record.copies) {
      if (copies[copyId] && copies[copyId] !== record.bankId) {
        throw new Error(`${copyId} is claimed as a copy by both ${copies[copyId]} and ${record.bankId}`);
      }
      copies[copyId] = record.bankId;
    }
  }
  const header = `// GENERATED by scripts/build-bank.mjs from content/bank/metadata/*.json. Do not hand-edit: a hand edit\n`
    + `// fails the "Generated slice" test (docs/QUESTION-BANK.md 4.9), which re-runs this script and diffs the\n`
    + `// result against this file's bytes.\nimport type { RuntimeMeta } from './types'\n\n`;
  const metaBody = `export const BANK_META: Readonly<Record<string, RuntimeMeta>> = Object.freeze(${JSON.stringify(meta, null, 2)})\n\n`;
  const copiesBody = `// Maps a copy's own deckId:questionId to the bank id that carries its metadata (4.3).\n`
    + `export const BANK_COPIES: Readonly<Record<string, string>> = Object.freeze(${JSON.stringify(copies, null, 2)})\n`;
  return `${header}${metaBody}${copiesBody}`;
}

function buildBankDecks(_records) {
  // Phase 3+ writes src/data/decks/bank/<subject>.ts from content/bank/approved/<subject>.json. Phase 2 ships no
  // approved questions yet (7.7), so this is a no-op unless a later phase's approved file already exists.
  const approvedDir = 'content/bank/approved';
  if (!existsSync(approvedDir)) return;
  const subjectsWithApproved = readdirSync(approvedDir).filter((f) => f.endsWith('.json'));
  for (const file of subjectsWithApproved) {
    const approved = JSON.parse(readFileSync(`${approvedDir}/${file}`, 'utf8'));
    if (Array.isArray(approved) && approved.length === 0) continue; // nothing to generate yet
    throw new Error(`${file} carries approved questions; scripts/build-bank.mjs needs its phase 3 deck-module writer wired in before this runs.`);
  }
}

const records = loadMetadataRecords();
if (records.length !== 150) {
  console.error(`BUILD_BANK FAIL: expected 150 metadata records across content/bank/metadata/, found ${records.length}`);
  process.exit(1);
}
const unrated = records.map((record) => [record.bankId, difficultyProblem(record)]).filter(([, problem]) => problem);
if (unrated.length > 0) {
  for (const [bankId, problem] of unrated) console.error(`BUILD_BANK FAIL: ${bankId} ${problem}`);
  console.error(`BUILD_BANK FAIL: ${unrated.length} of ${records.length} records lack a final difficulty level. Rate them before building.`);
  process.exit(1);
}
buildBankDecks(records);
const generated = renderModule(records);

if (CHECK) {
  const onDisk = existsSync(OUT_PATH) ? readFileSync(OUT_PATH, 'utf8') : null;
  if (onDisk !== generated) {
    console.error(`BUILD_BANK_CHECK FAIL: ${OUT_PATH} is stale. Run node --import tsx scripts/build-bank.mjs to regenerate.`);
    process.exit(1);
  }
  console.log(`BUILD_BANK_CHECK ok records=${records.length}`);
} else {
  mkdirSync('src/data/bank', { recursive: true });
  writeFileSync(OUT_PATH, generated);
  console.log(`BUILD_BANK wrote ${OUT_PATH} records=${records.length}`);
}
